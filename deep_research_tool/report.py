from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Dict, List

from .config import ResearchQuery, ResearchSettings
from .evidence import EvidenceLocker

if TYPE_CHECKING:
    from .researcher import ResearchIterationResult


@dataclass
class VerificationInsight:
    toc_item: str
    risk_score: float
    message: str


class ReportGenerator:
    def __init__(self, evidence_locker: EvidenceLocker, settings: ResearchSettings):
        self.evidence_locker = evidence_locker
        self.settings = settings

    def _assess_risk(self, iteration_results: List[ResearchIterationResult]) -> VerificationInsight:
        if not iteration_results:
            return VerificationInsight(toc_item="N/A", risk_score=1.0, message="No findings available.")
        latest = iteration_results[-1]
        evidence_count = len(latest.search_results)
        risk_score = max(0.0, 1.0 - evidence_count / max(1, self.settings.verification_sensitivity * 10))
        message = """
- Evidence count: {evidence_count}
- Risk score: {risk_score:.2f}
- Guidance: Focus verification on claims lacking citations and validate URLs manually.
""".strip()
        return VerificationInsight(toc_item=latest.toc_item, risk_score=risk_score, message=message)

    def generate(
        self, research_query: ResearchQuery, iterations: Dict[str, List[ResearchIterationResult]]
    ) -> str:
        lines = ["# Deep Research Report", ""]
        lines.append(f"**Brief:** {research_query.brief}")
        if research_query.requirements:
            lines.append(f"**Requirements:** {research_query.requirements}")
        if research_query.additional_documents:
            lines.append(f"**Additional documents:** {', '.join(research_query.additional_documents)}")
        lines.append("")

        lines.append("## Table of Contents")
        for idx, toc_item in enumerate(iterations.keys(), start=1):
            lines.append(f"{idx}. {toc_item}")
        lines.append("")

        lines.append("## Findings")
        for toc_item, iteration_results in iterations.items():
            lines.append(f"### {toc_item}")
            for result in iteration_results:
                lines.append(f"- **Iteration {result.iteration} Queries:** {', '.join(result.queries)}")
                for finding in result.findings:
                    lines.append(f"  - {finding}")
            lines.append("")

        lines.append("## Evidence Locker")
        for entry in self.evidence_locker.entries:
            lines.append(
                f"- [{entry.title}]({entry.url}) | Iteration {entry.iteration} | Section: {entry.toc_item} | Snippet: {entry.snippet}"
            )
        lines.append("")

        lines.append("## Verification Dashboard")
        for toc_item, iteration_results in iterations.items():
            insight = self._assess_risk(iteration_results)
            bar = "█" * int((1 - insight.risk_score) * 10)
            lines.append(f"### {toc_item}")
            lines.append(f"Confidence: {bar or '⚠️ low evidence'} ({1 - insight.risk_score:.2f})")
            lines.append(insight.message)
            lines.append("")

        lines.append("---")
        lines.append("Report generated by DeepResearchTool. Extend to DOCX/PDF as needed.")
        return "\n".join(lines)
